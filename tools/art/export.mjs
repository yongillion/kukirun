#!/usr/bin/env node
// =============================================================================
//  Art Forge exporter: renders tools/art/modules/*.js in headless Chromium and
//  writes PNGs to assets/img/ plus atlas metadata modules to src/data/.
//
//    node tools/art/export.mjs                 # all modules
//    node tools/art/export.mjs characters pets # selected modules
//
//  Requires Playwright (npm i -D playwright) with a Chromium build.
// =============================================================================
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { startServer } from '../serve.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
const IMG = path.join(ROOT, 'assets', 'img');
const DATA = path.join(ROOT, 'src', 'data');

async function loadPlaywright() {
  try { return await import('playwright'); } catch {}
  const guesses = ['/opt/npm-tools/node_modules/', path.join(ROOT, 'node_modules') + '/'];
  for (const g of guesses) {
    try { return createRequire(g)('playwright'); } catch {}
  }
  throw new Error('playwright not found — run: npm i -D playwright');
}

function camel(s) { return s.replace(/[^a-zA-Z0-9]+(.)/g, (_, c) => c.toUpperCase()).replace(/^./, (c) => c.toUpperCase()); }

async function main() {
  let mods = process.argv.slice(2).filter((a) => !a.startsWith('--'));
  const all = fs.readdirSync(path.join(HERE, 'modules')).filter((f) => f.endsWith('.js') && !f.startsWith('_')).map((f) => f.replace(/\.js$/, ''));
  if (!mods.length) mods = all;
  const optimize = !process.argv.includes('--fast');

  const server = await startServer(0, ROOT);
  const port = server.address().port;
  const { chromium } = await loadPlaywright();
  const browser = await chromium.launch({ args: ['--disable-web-security'] });
  const page = await browser.newPage();
  page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') console.log('[page]', m.type(), m.text()); });
  page.on('pageerror', (e) => console.log('[pageerror]', e.message));
  await page.goto(`http://127.0.0.1:${port}/tools/art/forge.html?headless=1`);
  await page.waitForFunction(() => window.__forgeReady === true);

  let sharp = null;
  if (optimize) { try { sharp = createRequire('/opt/npm-tools/node_modules/')('sharp'); } catch { try { sharp = (await import('sharp')).default; } catch {} } }

  for (const mod of mods) {
    const t0 = Date.now();
    const results = await page.evaluate(async (m) => {
      const r = await window.runForge([m]);
      return r;
    }, mod);
    const meta = {};
    for (const r of results) {
      const out = path.join(IMG, r.path + '.png');
      fs.mkdirSync(path.dirname(out), { recursive: true });
      let buf = Buffer.from(r.dataURL.split(',')[1], 'base64');
      if (sharp) {
        try { buf = await sharp(buf).png({ compressionLevel: 9, adaptiveFiltering: true, palette: false }).toBuffer(); } catch (e) { console.log('sharp failed', e.message); }
      }
      fs.writeFileSync(out, buf);
      meta[r.id] = { ...r.meta, src: 'assets/img/' + r.path + '.png' };
      console.log(`  ${mod}/${r.id} -> assets/img/${r.path}.png  ${r.width}x${r.height}  ${(buf.length / 1024).toFixed(0)}KB`);
    }
    const varName = 'ATLAS_' + mod.toUpperCase().replace(/[^A-Z0-9]/g, '_');
    const js = `// AUTO-GENERATED by tools/art/export.mjs from tools/art/modules/${mod}.js — do not edit by hand\nexport const ${varName} = ${JSON.stringify(meta, null, 1)};\n`;
    fs.writeFileSync(path.join(DATA, `atlas_${mod}.js`), js);
    console.log(`[${mod}] ${results.length} outputs in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
  }
  await browser.close();
  server.close();

  // regenerate src/data/atlas.js index
  const files = fs.readdirSync(DATA).filter((f) => /^atlas_.+\.js$/.test(f)).sort();
  const lines = ['// AUTO-GENERATED by tools/art/export.mjs — merges every src/data/atlas_*.js'];
  const names = [];
  for (const f of files) {
    const mod = f.replace(/^atlas_|\.js$/g, '');
    const v = 'ATLAS_' + mod.toUpperCase().replace(/[^A-Z0-9]/g, '_');
    lines.push(`import { ${v} } from './${f}';`);
    names.push(v);
  }
  lines.push(`export const ATLAS = Object.assign({}, ${names.join(', ')});`);
  fs.writeFileSync(path.join(DATA, 'atlas.js'), lines.join('\n') + '\n');
  console.log('wrote src/data/atlas.js with', names.length, 'modules');
}

main().catch((e) => { console.error(e); process.exit(1); });
