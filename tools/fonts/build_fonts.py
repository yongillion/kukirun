#!/usr/bin/env python3
"""
Build the game's font pack.

Fonts (all SIL Open Font License 1.1 — redistribution allowed):
  * DDDisplay : Noto Sans CJK KR Black   (titles, buttons, big labels)
  * DDBold    : Noto Sans CJK KR Bold    (body text, descriptions)
  * DDNum     : Poppins Bold             (numbers, latin headings)

The Korean faces are subset to every Hangul syllable/character that appears in
the game's source (src/**/*.js, tools/art/**/*.js) plus the 2,350 common KS X 1001
syllables, ASCII and common punctuation/symbols, so any normal Korean text renders.

Outputs
  assets/fonts/DDDisplay.woff, DDBold.woff, DDNum.woff
  assets/fonts/fontpack.js   (window.__DD_FONTS__ = {name: base64-woff, ...})
     -> loaded with a classic <script> so it also works from file://

Usage:  python3 tools/fonts/build_fonts.py [--full]   (--full = all 11,172 syllables)
"""
import base64
import glob
import io
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTCollection, TTFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'assets', 'fonts')
NOTO_DIR = '/usr/share/fonts/opentype/noto'
POPPINS = '/usr/share/fonts/truetype/google-fonts/Poppins-Bold.ttf'

# allow overriding font source locations on another machine
NOTO_DIR = os.environ.get('DD_NOTO_DIR', NOTO_DIR)
POPPINS = os.environ.get('DD_POPPINS', POPPINS)


def ksx1001_syllables():
    out = []
    for cp in range(0xAC00, 0xD7A4):
        try:
            chr(cp).encode('euc-kr')
            out.append(cp)
        except UnicodeEncodeError:
            pass
    return out


def source_chars():
    chars = set()
    pats = [os.path.join(ROOT, 'src', '**', '*.js'), os.path.join(ROOT, 'tools', 'art', '**', '*.js')]
    for pat in pats:
        for f in glob.glob(pat, recursive=True):
            try:
                with open(f, encoding='utf-8') as fh:
                    chars.update(ord(ch) for ch in fh.read())
            except Exception:
                pass
    return chars


def base_unicodes():
    u = set(range(0x20, 0x7F))
    u.update(range(0xA0, 0x100))
    u.update(range(0x2010, 0x2070))   # general punctuation
    u.update(range(0x2190, 0x2200))   # arrows
    u.update([0x2605, 0x2606, 0x2665, 0x2661, 0x266A, 0x266B, 0x2714, 0x2716, 0x2715, 0x00D7, 0x2022, 0x25B6, 0x25C0, 0x25B2, 0x25BC, 0x2B50])
    u.update(range(0x3000, 0x3040))   # CJK punctuation
    u.update(range(0x3131, 0x318F))   # Hangul compatibility jamo
    u.update(range(0xFF01, 0xFF5F))   # fullwidth forms
    return u


def load_noto_kr(weight):
    path = os.path.join(NOTO_DIR, f'NotoSansCJK-{weight}.ttc')
    coll = TTCollection(path)
    for font in coll.fonts:
        names = [n.toUnicode() for n in font['name'].names if n.nameID in (1, 4)]
        if any('CJK KR' in n for n in names):
            buf = io.BytesIO()
            font.save(buf)
            buf.seek(0)
            return TTFont(buf)
    raise RuntimeError('KR face not found in ' + path)


def subset_font(font, unicodes, name):
    opts = subset.Options()
    opts.flavor = 'woff'
    opts.layout_features = ['*']
    opts.name_IDs = ['*']
    opts.name_languages = ['*']
    opts.notdef_outline = True
    opts.hinting = False
    opts.desubroutinize = False
    sub = subset.Subsetter(options=opts)
    sub.populate(unicodes=sorted(unicodes))
    sub.subset(font)
    path = os.path.join(OUT, name + '.woff')
    font.flavor = 'woff'
    font.save(path)
    return path


def main():
    os.makedirs(OUT, exist_ok=True)
    full = '--full' in sys.argv
    hangul = set(range(0xAC00, 0xD7A4)) if full else set(ksx1001_syllables())
    used = source_chars()
    kr_set = base_unicodes() | hangul | {c for c in used if 0xAC00 <= c <= 0xD7A3 or 0x3130 <= c <= 0x318F}
    latin_set = base_unicodes() & set(range(0x20, 0x2200))

    outputs = {}
    for name, weight in (('DDDisplay', 'Black'), ('DDBold', 'Bold')):
        f = load_noto_kr(weight)
        p = subset_font(f, kr_set, name)
        outputs[name] = p
    pop = TTFont(POPPINS)
    outputs['DDNum'] = subset_font(pop, latin_set, 'DDNum')

    lines = ['/* AUTO-GENERATED by tools/fonts/build_fonts.py — Noto Sans CJK KR (Black/Bold) & Poppins Bold, SIL OFL 1.1 */',
             'window.__DD_FONTS__ = {']
    for name, p in outputs.items():
        with open(p, 'rb') as fh:
            b64 = base64.b64encode(fh.read()).decode('ascii')
        lines.append(f'  "{name}": "{b64}",')
        print(f'{name}: {os.path.getsize(p)/1024:.1f} KB')
    lines.append('};')
    with open(os.path.join(OUT, 'fontpack.js'), 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines) + '\n')
    print('fontpack.js', os.path.getsize(os.path.join(OUT, 'fontpack.js')) / 1024, 'KB')


if __name__ == '__main__':
    main()
